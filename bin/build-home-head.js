import { build, transform } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

export async function buildHomeHead(directory) {
  const previews = JSON.parse(await readFile('src/assets/home-hero-previews.json', 'utf8'));
  const previewCss = Object.entries(previews).map(([scene, { dataUrl }]) =>
    `html[data-home-hero-scene="${scene}"]{--home-hero-preview:url("${dataUrl}")}`
  ).join('\n');
  const css = await transform(previewCss + '\n' + await readFile('src/inline/home-hero.css', 'utf8'), {
    loader: 'css', minify: true,
  });
  const script = await build({
    entryPoints: ['src/inline/home-hero.ts'], bundle: true, minify: true,
    format: 'iife', target: 'es2019', write: false,
  });
  const snippet = `<!-- Generated by bin/build-home-head.js; edit sources in the repo. -->\n<style>${css.code.trim()}</style>\n<script>${script.outputFiles[0].text.trim()}</script>\n`;
  await mkdir(path.join(directory, 'pages'), { recursive: true });
  await writeFile(path.join(directory, 'pages/home-head.html'), snippet);
}
